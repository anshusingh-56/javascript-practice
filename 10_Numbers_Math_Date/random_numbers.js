// Random Numbers Generation

// Random decimal between 0 (inclusive) and (exclusive)
console.log("Random Decimal: ", Math.random());

// Random integer between 1 and 10
const randomNumber = Math.floor(Math.random() * 10) + 1;
console.log("Random Number (1-10): ", randomNumber);

// Random integer between 1 and 100
const randomValue = Math.floor(Math.random() * 100) + 1;
console.log("Random Value (1-100): ", randomValue);

// Random integer between 1 and 1000
const randomValue = Math.floor(Math.random() * 1000) + 1;
console.log("Random Value (1-1000): ", randomValue);
