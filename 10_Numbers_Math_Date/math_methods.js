// Math Object Methods

// sqrt() → Returns the square root of a number
console.log("Square Root: ", Math.sqrt(49));

// pow(base, exponent) → Returns the value of a number raised to a power
console.log("Power: ", Math.pow(2,5));

// round() → Rounds a number to the nearest integer
console.log("Round: ", Math.round(4.7));

// floor() → Rounds a number down to the nearest integer
console.log("Floor: ", Math.floor(4.9));

// ceil() → Rounds a number up to the nearest integer
console.log("Ceil: ", Math.ceil(4.1));

// trunc() → Removes the decimal part and returns the integer part
console.log("Truncate: ", Math.trunc(4.9));

// abs() → Returns the absolute (positive) value of a number
console.log("Absolute: ", Math.abs(-24));

// max() → Returns the largest value from a list of numbers
console.log("Maximum: ", Math.max(10,20,30));

// min() → Returns the smallest value from a list of numbers
console.log("Minimum: ", Math.min(10,20,30));

// PI → Returns the value of Pi (π)
console.log("PI:", Math.PI);