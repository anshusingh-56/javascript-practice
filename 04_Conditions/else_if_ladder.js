// Using the else-if ladder

let marks = 85;

if(marks >= 90) {
    console.log("Grade A+");
}
else if(marks >= 80){
    console.log("Grade A")
}
else if(marks >= 70){
    console.log("Grade B");
}
else if(marks >= 60){
    console.log("Grade C");
}
else if(marks >= 40){
    console.log("Grade D");
}
else {
    console.log("Grade F - Fail");
}

// Check temperature

let temperature = 15;

if (temperature >= 35) {
    console.log("Very hot");
} else if (temperature >= 25) {
    console.log("Warm");
} else if (temperature >= 15) {
    console.log("Cool");
} else {
    console.log("Cold");
}