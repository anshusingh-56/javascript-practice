// Using if-else statement

let age = 16;

if(age >= 18) {
    console.log("You are eligible to vote");
}
else{
    console.log("You are not eligible to vote");
}

// check whether a number is even or odd

let num = 25;

if(num % 2 === 0){
    console.log("Even number");
}
else{
    console.log("Odd number");
}

