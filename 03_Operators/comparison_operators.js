// Comparison operators in JavaScript

let a = 10;
let b = 5;

console.log("Equal: ", a == b);
console.log("strict equal: ", a === b);
console.log("Not equal: ", a != b);
console.log("Strict not equal: ", a !== b);
console.log("Greater than: ", a > b);
console.log("Smaller than: ", a < b);
console.log("Greater than or equal: ", a >= b);
console.log("Smaller than or equal: ", a <= b);

// Difference between == and ===
console.log("Loose equality: ", 5 == "5");
console.log("Strict equality: ", 5 === "5");
