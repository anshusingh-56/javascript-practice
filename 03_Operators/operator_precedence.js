// Operator precedence in JavaScript

// Multiplication happens before addition
console.log(10 + 5 * 2);

// Parentheses change the evaluation order
console.log((10 + 5) * 2);

// Division and multiplication
console.log(20 / 5 * 2);

// Addition and subtraction
console.log(10 - 3 + 2);

// Exponentiation
console.log(2 + 3 ** 2);

// Using parentheses for clarity
console.log((2 + 3) ** 2);