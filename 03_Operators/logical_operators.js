// Logical operators in JavaScript

let age = 20;
let hasId = true;

// AND operator
console.log("AND: ", age >= 18 && hasId);

// OR operator
console.log("OR: ", age < 18 || hasId);

// NOT operator
console.log("NOT; ", !hasId);

// Multiple conditions
let marks = 85;

console.log("Pased: ", marks >= 40 && marks <= 100);