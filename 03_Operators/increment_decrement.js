// Increment and decrement operators

let  a = 5;

// Post increment 
console.log("Post increment: ", a++);
console.log("Current value: ", a);

// Pre increment 
console.log("Pre increment: ", ++a);

// Post decrement 
console.log("Post decrement: ", a--);
console.log("Current value: ", a);

// pre decrement
console.log("Pre decrement: ", --a);
