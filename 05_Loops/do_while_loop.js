// Using the do-while loop

// 1. Print numbers from 1 to 5
let i = 1;

do {
    console.log(i);
    i++;
} while (i <= 5);

console.log("---------------");

// 2. Condition is false initially
let number = 10;

do {
    console.log("This runs at least once.");
    number++;
} while (number < 5);