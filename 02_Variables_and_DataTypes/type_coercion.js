// Type coercion in JavaScript

// 1. Number and string
console.log(10 + "5");

// 2. Subtraction with a numeric string
console.log("10" - 5);

// 3. Multiplication with a numeric string
console.log("4" * 3);

// 4. Addition with a Boolean
console.log(10 + true);

// 5. String and Boolean
console.log("Hello " + true);

// 6. Equality comparison
console.log(5 == "5");

// 7. Strict equality comparison
console.log(5 === "5");