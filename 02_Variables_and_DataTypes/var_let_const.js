// Variables in JavaScript

// 1. Using var

var studentName = "Anshu";
console.log(studentName);

var studentName = "Shikha";
console.log(studentName);

// 2. Using let

let age = 18;
console.log(age);

age = 19;
console.log(age);

// 3. Const

const country = "India";
console.log(country);

